/** 검색: 낱말이나 묶음 이름에 검색어가 들어간 이모지(겹치면 한 번만) */
export function searchEmoji(query: string): string[] {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const found = new Set<string>();
  for (const category of EMOJI_CATEGORIES) for (const [emoji, text] of category.items) {
    const hay = `${text} ${category.label}`.toLocaleLowerCase();
    if (words.every((w) => hay.includes(w))) found.add(emoji);
  }
  return [...found];
}

/** 이 기기에서 최근 고른 이모지(이 기기 편의용, 저장 실패해도 화면은 동작) */
const RECENT_KEY = "datemap:recent-emoji";
export function recentEmoji(): string[] {
  try { const value = JSON.parse(localStorage.getItem(RECENT_KEY) ?? "[]"); return Array.isArray(value) ? value.filter((v): v is string => typeof v === "string").slice(0, 7) : []; }
  catch { return []; }
}
export function rememberEmoji(emoji: string) {
  try { localStorage.setItem(RECENT_KEY, JSON.stringify([emoji, ...recentEmoji().filter((e) => e !== emoji)].slice(0, 7))); }
  catch { /* 저장소를 못 써도 고르기는 그대로 */ }
}
